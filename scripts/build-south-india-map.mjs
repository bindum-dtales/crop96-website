/**
 * Regenerates `src/lib/southIndia.ts` from published boundary data.
 *
 * The map in `components/ui/SouthIndiaMap.tsx` is not drawn — it is projected
 * from real geometry, and this is the step that does it. Run it only when the
 * boundaries themselves need to change (a new source, a different projection,
 * a different simplification tolerance); the emitted file is checked in, so
 * nothing at build or run time depends on this script.
 *
 *   npm i --no-save polygon-clipping
 *   curl -sSLo /tmp/india.geojson \
 *     https://raw.githubusercontent.com/udit-001/india-maps-data/main/geojson/india.geojson
 *   node scripts/build-south-india-map.mjs /tmp/india.geojson [tolerance]
 *
 * What it does, in order: keep the six state-level features, project them to
 * Web Mercator, fit them to a 900-unit-tall box, simplify with
 * Douglas–Peucker (default 0.35 user units — enough to drop collinear noise,
 * not enough to move a coastline), union the six into one silhouette so the
 * coast can be stroked without also stroking every interior border, and pad
 * the viewBox to leave sea for the Kerala and Goa labels.
 */
import fs from 'node:fs'
import polygonClipping from 'polygon-clipping'

const SRC = process.argv[2] ?? '/tmp/india.geojson'
const TOL = Number(process.argv[3] ?? 0.35)
const OUT = new URL('../src/lib/southIndia.ts', import.meta.url)

const SOUTH = ['Karnataka', 'Kerala', 'Tamil Nadu', 'Andhra Pradesh', 'Telangana', 'Goa']
const KEY = {
  Karnataka: 'karnataka',
  Kerala: 'kerala',
  'Tamil Nadu': 'tamilNadu',
  'Andhra Pradesh': 'andhraPradesh',
  Telangana: 'telangana',
  Goa: 'goa',
}
/** Sea on the west for the two labels that cannot fit inside their state. */
const PAD = { l: 126, r: 22, t: 26, b: 34 }
/** Goa drawn first: it is small enough for a neighbour to paint over it. */
const ORDER = ['goa', 'karnataka', 'telangana', 'andhraPradesh', 'kerala', 'tamilNadu']

const raw = JSON.parse(fs.readFileSync(SRC, 'utf8'))
// The file carries districts *and* dissolved states; the states are the
// features with no district of their own.
const feats = raw.features.filter(
  (f) => !f.properties.district && SOUTH.includes(f.properties.st_nm),
)
if (feats.length !== SOUTH.length) throw new Error(`expected ${SOUTH.length} states, got ${feats.length}`)

const R = 180 / Math.PI
const merc = ([lng, lat]) => [lng, R * Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 180 / 2))]

const ringArea = (r) => {
  let a = 0
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) a += r[j][0] * r[i][1] - r[i][0] * r[j][1]
  return Math.abs(a / 2)
}

// Offshore islets below this area are visual noise at any size we render at.
const MIN_AREA = 0.0004
const projected = feats.map((f) => ({
  name: f.properties.st_nm,
  polys: (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates)
    .map((poly) => poly.map((ring) => ring.map(merc)).filter((ring) => ring.length > 3))
    .filter((poly) => poly.length && ringArea(poly[0]) > MIN_AREA),
}))

const all = projected.flatMap((s) => s.polys.flat(2))
const xs = all.map((p) => p[0])
const ys = all.map((p) => p[1])
const [x0, x1, y0, y1] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)]
const H = 900
const k = H / (y1 - y0)
const W = +((x1 - x0) * k).toFixed(1)
const to = ([x, y]) => [(x - x0) * k, (y1 - y) * k]

const seg = (p, a, b) => {
  const dx = b[0] - a[0]
  const dy = b[1] - a[1]
  const l = dx * dx + dy * dy
  const t = l ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l)) : 0
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy))
}
const dp = (pts, tol) => {
  if (pts.length < 3) return pts
  let idx = 0
  let max = 0
  for (let i = 1; i < pts.length - 1; i++) {
    const d = seg(pts[i], pts[0], pts[pts.length - 1])
    if (d > max) {
      max = d
      idx = i
    }
  }
  return max > tol
    ? [...dp(pts.slice(0, idx + 1), tol).slice(0, -1), ...dp(pts.slice(idx), tol)]
    : [pts[0], pts[pts.length - 1]]
}

const round = (n) => {
  const v = Math.round(n * 10) / 10
  return Object.is(v, -0) ? 0 : v
}
const ringToPath = (ring) =>
  'M' +
  dp(ring.map(to), TOL)
    .map(([x, y]) => `${round(x)} ${round(y)}`)
    .join('L') +
  'Z'
const polysToPath = (polys) => polys.map((poly) => poly.map(ringToPath).join('')).join('')

const union = polygonClipping.union(...projected.map((s) => s.polys))
const outline = polysToPath(union.map((poly) => poly.filter((r) => ringArea(r) > MIN_AREA)))
const states = Object.fromEntries(projected.map((s) => [KEY[s.name], polysToPath(s.polys)]))

const VB = {
  x: -PAD.l,
  y: -PAD.t,
  w: +(W + PAD.l + PAD.r).toFixed(1),
  h: +(H + PAD.t + PAD.b).toFixed(1),
}

fs.writeFileSync(
  OUT,
  `/**
 * South India — geographic path data.
 *
 * GENERATED by scripts/build-south-india-map.mjs; edit that, not this.
 * Source: state boundaries published by udit-001/india-maps-data (Census 2011
 * lineage, post-2014 Telangana split), projected to Web Mercator and
 * simplified with Douglas-Peucker at ${TOL} user units — enough to drop
 * collinear noise, not enough to move a coastline. \`OUTLINE\` is the polygon
 * union of the six states, so the coast can be stroked without also stroking
 * every interior border.
 *
 * Coordinates live in the projection's own units; \`project()\` maps any
 * lng/lat into the same space, which is how markers and labels stay pinned to
 * real places rather than to eyeballed percentages.
 */

export const VIEW_BOX = { x: ${VB.x}, y: ${VB.y}, width: ${VB.w}, height: ${VB.h} } as const

/** viewBox string, and the aspect the container must hold for the HTML overlay to line up. */
export const VIEW_BOX_ATTR = '${VB.x} ${VB.y} ${VB.w} ${VB.h}'
export const ASPECT = ${(VB.w / VB.h).toFixed(4)}

const LNG_0 = ${x0}
const MERC_Y1 = ${y1}
const SCALE = ${k}

const mercatorY = (lat: number) =>
  (180 / Math.PI) * Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360))

/** Longitude/latitude → the same user space the paths are drawn in. */
export function project(lng: number, lat: number): { x: number; y: number } {
  return { x: (lng - LNG_0) * SCALE, y: (MERC_Y1 - mercatorY(lat)) * SCALE }
}

/** The same point as a percentage of the viewBox — for HTML overlaid on the svg. */
export function projectPercent(lng: number, lat: number): { left: string; top: string } {
  const { x, y } = project(lng, lat)
  return {
    left: \`\${((x - VIEW_BOX.x) / VIEW_BOX.width) * 100}%\`,
    top: \`\${((y - VIEW_BOX.y) / VIEW_BOX.height) * 100}%\`,
  }
}

export type StateKey = ${ORDER.map((key) => `'${key}'`).join(' | ')}

/** Coastline and land border of the six states as one silhouette. */
export const OUTLINE =
  '${outline}'

/** Drawn back to front: Goa is small enough to be overpainted otherwise. */
export const STATE_PATHS: Record<StateKey, string> = {
${ORDER.map((key) => `  ${key}:\n    '${states[key]}',`).join('\n')}
}
`,
)

console.log(`viewBox ${VB.x} ${VB.y} ${VB.w} ${VB.h} | tolerance ${TOL}`)
for (const [key, d] of Object.entries(states)) console.log(`  ${key.padEnd(14)} ${d.length} chars`)
console.log(`  ${'outline'.padEnd(14)} ${outline.length} chars`)
